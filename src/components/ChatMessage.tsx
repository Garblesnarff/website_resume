import React from 'react';
import type { ChatMessage, MessageContent } from '../types';
import { getChatImagePath } from '../config';
import ToolCallDisplay from './ToolCallDisplay';
import CodeBlockDisplay from './CodeBlockDisplay';

interface ChatMessageProps {
  message: ChatMessage;
}

const Text = ({ value }: { value: string }) => (
  <p className="whitespace-pre-wrap break-words text-[1rem] leading-relaxed">{value.trim()}</p>
);

const processText = (text: string) => {
  if (!text) return null;

  if (text.includes('<pasted_content>') && text.includes('</pasted_content>')) {
    const parts = text.split(/<pasted_content>|<\/pasted_content>/);
    return (
      <>
        {parts[0]?.trim() && <Text value={parts[0]} />}
        {parts[1] && (
          <details className="group my-3 rounded-[3px] border border-night-line bg-night/60">
            <summary className="cursor-pointer select-none px-4 py-2 font-ui font-bold text-fog hover:text-birch">
              Pasted content
            </summary>
            <div tabIndex={0} className="max-h-96 overflow-auto border-t border-night-line px-4 py-3">
              <pre className="whitespace-pre-wrap font-serif text-[0.95rem] text-fog">{parts[1]}</pre>
            </div>
          </details>
        )}
        {parts[2]?.trim() && <Text value={parts[2]} />}
      </>
    );
  }

  return <Text value={text} />;
};

const ChatMessage: React.FC<ChatMessageProps> = ({ message }) => {
  const isUser = message.speaker === 'user';

  if (message.imagePath) {
    return (
      <figure className="py-2">
        <img
          src={getChatImagePath(message.imagePath)}
          alt="An image Aurora generated with Gemini to show its internal state"
          className="mx-auto max-h-[28rem] w-auto rounded-[3px] object-contain"
          loading="lazy"
        />
        <figcaption className="mt-2 text-center text-sm text-fog/80">Generated by Aurora through the Gemini image tool</figcaption>
      </figure>
    );
  }

  return (
    <div className="grid gap-1 sm:grid-cols-[5.5rem_1fr] sm:gap-5">
      <div className={`font-ui text-[0.95rem] font-bold sm:pt-0.5 ${isUser ? 'text-sodium' : 'text-fog'}`}>
        {isUser ? 'Rob' : 'Claude'}
      </div>
      <div className={`min-w-0 space-y-3 ${isUser ? 'text-birch' : 'text-birch/85'}`}>
        {message.content.map((block: MessageContent, index: number) => (
          <React.Fragment key={index}>
            {block.type === 'text' && processText(block.value)}
            {block.type === 'tool_call' && <ToolCallDisplay toolCall={block.value} />}
            {block.type === 'code' && <CodeBlockDisplay code={block.value} />}
          </React.Fragment>
        ))}
      </div>
    </div>
  );
};

export default ChatMessage;
